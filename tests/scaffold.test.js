import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import test from 'node:test';
import { initProject } from '../src/scaffold.mjs';
import { UsageError } from '../src/config.mjs';
import { runCli, tempDir } from './helpers.mjs';

const MINIMAL_FILES = [
  '.gitattributes',
  '.github/workflows/verify.yml',
  '.gitignore',
  '.node-version',
  'README.md',
  'client.js',
  'cordis.patch.yml',
  'icon.svg',
  'index.js',
  'locale/en.json',
  'locale/zh.json',
  'package.json',
  'tests/manifest.test.js',
];

async function scaffold(matrix, name = 'kit-demo-plugin') {
  const parent = await tempDir();
  const dir = join(parent, 'demo-plugin');
  const result = await initProject({ dir, matrix, name });
  return { dir, result };
}

test('init minimal writes the documented skeleton', async () => {
  const { dir, result } = await scaffold('minimal');
  assert.deepEqual(result.files, MINIMAL_FILES);
  assert.equal(result.packageName, 'kit-demo-plugin');
  const manifest = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  assert.equal(manifest.dsh.bundle.patch, './cordis.patch.yml');
  assert.equal(manifest.dsh.client.platform, 'web');
  assert.deepEqual(manifest.dshPluginKit.artifacts, []);
  assert.equal(manifest.exports['./client'], './client.js');
  assert.equal(manifest.dshPluginKit.locale.required[1], 'zh');
  const en = JSON.parse(await readFile(join(dir, 'locale/en.json'), 'utf8'));
  const zh = JSON.parse(await readFile(join(dir, 'locale/zh.json'), 'utf8'));
  assert.deepEqual(Object.keys(en.meta).sort(), Object.keys(zh.meta).sort());
});

test('init built adds a source entry and a producer artifact', async () => {
  const { dir } = await scaffold('built');
  const browser = await readFile(join(dir, 'src/browser-entry.js'), 'utf8');
  const client = await readFile(join(dir, 'client.js'), 'utf8');
  assert.ok(client.startsWith('// Generated by scripts/build.mjs'));
  assert.equal(client, '// Generated by scripts/build.mjs from src/browser-entry.js. Do not edit directly.\n' + browser);
  const manifest = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  assert.deepEqual(manifest.dshPluginKit.artifacts, [{ file: 'client.js', produce: 'scripts/build.mjs' }]);
  const check = runCli(['artifacts', '--check', '--root', dir]);
  assert.equal(check.status, 0, check.stdout + check.stderr);
});

test('init refuses a non-empty directory', async () => {
  const { dir } = await scaffold('minimal');
  await assert.rejects(() => initProject({ dir, matrix: 'minimal' }), UsageError);
  const viaCli = runCli(['init', '--dir', dir, '--yes']);
  assert.equal(viaCli.status, 2);
  assert.match(viaCli.stderr, /non-empty directory/);
});

test('init rejects an unknown matrix and an invalid package name', async () => {
  const parent = await tempDir();
  await assert.rejects(() => initProject({ dir: join(parent, 'a'), matrix: 'ui' }), UsageError);
  const second = await tempDir();
  await assert.rejects(() => initProject({ dir: join(second, 'b'), matrix: 'minimal', name: 'Bad Name' }), UsageError);
});

test('init without --yes and without a TTY exits 2', async () => {
  const parent = await tempDir();
  const result = runCli(['init', '--dir', join(parent, 'plugin'), '--matrix', 'minimal']);
  assert.equal(result.status, 2);
  assert.match(result.stderr, /--yes/);
});

test('a scaffolded minimal plugin passes check and verify', async () => {
  const { dir } = await scaffold('minimal');
  const check = runCli(['check', '--root', dir]);
  assert.equal(check.status, 0, check.stdout + check.stderr);
  const verify = runCli(['verify', '--root', dir]);
  assert.equal(verify.status, 0, verify.stdout + verify.stderr);
  assert.match(verify.stdout, /verify: ok/);
});

test('a scaffolded built plugin passes check and verify end to end', async () => {
  const { dir } = await scaffold('built');
  const check = runCli(['check', '--root', dir]);
  assert.equal(check.status, 0, check.stdout + check.stderr);
  const verify = runCli(['verify', '--root', dir]);
  assert.equal(verify.status, 0, verify.stdout + verify.stderr);
  for (const stage of ['check', 'artifacts', 'pack', 'screenshots', 'verify: ok']) {
    assert.ok(verify.stdout.includes(stage), 'verify output is missing stage: ' + stage);
  }
});

test('the CLI init --yes writes a scaffold and prints the file list', async () => {
  const parent = await tempDir();
  const dir = join(parent, 'cli-demo');
  const result = runCli(['init', '--dir', dir, '--yes', '--matrix', 'minimal']);
  assert.equal(result.status, 0, result.stderr);
  assert.match(result.stdout, /init: scaffolded/);
  assert.match(result.stdout, /locale\/en\.json/);
});

test('a stale generated client fails the scaffold artifact check', async () => {
  const { dir } = await scaffold('built');
  await writeFile(join(dir, 'client.js'), '// tampered\n');
  const check = runCli(['artifacts', '--check', '--root', dir]);
  assert.equal(check.status, 1);
  assert.equal(await readFile(join(dir, 'client.js'), 'utf8'), '// tampered\n');
});

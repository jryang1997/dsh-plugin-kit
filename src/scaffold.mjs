import { mkdir, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { UsageError } from './config.mjs';
import { isNonEmptyDir } from './util.mjs';

const MATRICES = ['minimal', 'built'];
const NODE_VERSION = '24.19.0';
const KIT_PACKAGE = '@jryang1997/dsh-plugin-kit';
const KIT_RANGE = '^1.0.0';
const BUILD_BANNER = '// Generated by scripts/build.mjs from src/browser-entry.js. Do not edit directly.';

function lines(list) {
  return list.join('\n') + '\n';
}

function derivePackageName(dir) {
  const raw = basename(resolve(dir)).toLowerCase();
  const cleaned = raw.replace(/[^a-z0-9._-]+/g, '-').replace(/^-+|-+$/g, '');
  if (cleaned === '' || cleaned === '.' || cleaned === '..') return 'dsh-plugin-demo';
  return cleaned;
}

function shortIdOf(packageName) {
  const bare = packageName.includes('/') ? packageName.split('/').pop() : packageName;
  const cleaned = bare.toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
  return cleaned === '' ? 'dsh-plugin-demo' : cleaned;
}

function titleOf(packageName) {
  const bare = packageName.includes('/') ? packageName.split('/').pop() : packageName;
  const words = bare.replace(/^dsh[-_]/, '').split(/[-_]+/).filter(Boolean);
  if (words.length === 0) return 'DSH plugin';
  return words.map(word => word.charAt(0).toUpperCase() + word.slice(1)).join(' ');
}


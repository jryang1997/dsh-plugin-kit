function indexSource(packageName) {
  return lines([
    '/**',
    ' * Host half of ' + packageName + '.',
    ' *',
    ' * Keep this half minimal unless the plugin needs a Config schema, a cordis service,',
    ' * or file work. Most DSH plugin behaviour lives in client.js.',
    ' */',
    'export const name = ' + "'" + packageName + "'" + ';',
    '',
    'export function apply() {',
    '  // Nothing to set up on the Host yet.',
    '}',
  ]);
}

function clientSource(packageName) {
  return lines([
    '/**',
    ' * Client half of ' + packageName + '.',
    ' *',
    ' * DSH loads this file through exports["./client"]. The loader hands the factory a',
    ' * require() for host packages; declare the services this plugin needs in inject,',
    ' * then register slots or effects in apply.',
    ' */',
    'window.__ModuleLoader__.load({',
    "  id: '" + packageName + "',",
    '  factory(require) {',
    "    const React = require('react');",
    "    const inject = ['slots'];",
    '',
    '    function Placeholder() {',
    "      return React.createElement('span', { hidden: true, 'data-plugin': '" + packageName + "' });",
    '    }',
    '',
    '    function apply(ctx) {',
    "      ctx.slots.inject('shell.overlay', () => ctx.slots.register({",
    "        name: 'shell.overlay',",
    "        id: '" + packageName + "',",
    '        order: 100,',
    '      }, Placeholder));',
    '    }',
    '',
    '    return { inject, apply };',
    '  },',
    '});',
  ]);
}

function cordisPatch(packageName) {
  return lines([
    '- insert:',
    '    - id: ' + shortIdOf(packageName),
    "      name: '" + packageName + "'",
    '      config: {}',
  ]);
}

